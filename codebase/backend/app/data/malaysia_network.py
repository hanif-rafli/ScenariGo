def haversine_distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculates great-circle distance between two GPS coordinates in kilometers."""
    radius_km = 6371.0
    dlat = math.radians(lat2 - lat1)
    dlon = math.radians(lon2 - lon1)
    a = (
        math.sin(dlat / 2.0) ** 2
        + math.cos(math.radians(lat1))
        * math.cos(math.radians(lat2))
        * math.sin(dlon / 2.0) ** 2
    )
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))
    return radius_km * c


def road_distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Estimates Malaysian highway driving distance using a 1.25 winding detour factor."""
    return round(haversine_distance_km(lat1, lon1, lat2, lon2) * 1.25, 1)


