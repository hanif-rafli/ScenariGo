# In-memory route cache for custom points
_ROAD_CACHE: dict[str, list[tuple[float, float]]] = {}


def fetch_dynamic_road_path(
    c1: tuple[float, float],
    c2: tuple[float, float],
    timeout_s: float = 1.5,
) -> tuple[list[tuple[float, float]], float]:
    """Fetches real-world driving geometry from OSRM for dynamic custom coordinates.
    
    Falls back gracefully to interpolated road coordinates if offline or timeout.
    """
    cache_key = f"{c1[0]:.4f},{c1[1]:.4f}_{c2[0]:.4f},{c2[1]:.4f}"
    if cache_key in _ROAD_CACHE:
        pts = _ROAD_CACHE[cache_key]
        return pts, road_distance_km(c1[0], c1[1], c2[0], c2[1])

    url = f"http://router.project-osrm.org/route/v1/driving/{c1[1]},{c1[0]};{c2[1]},{c2[0]}?overview=simplified&geometries=geojson"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "ScenariGo/1.0"})
        with urllib.request.urlopen(req, timeout=timeout_s) as resp:
            data = json.loads(resp.read().decode())
            coords = data["routes"][0]["geometry"]["coordinates"]
            dist_km = round(data["routes"][0]["distance"] / 1000.0, 1)
            pts = [(round(lat, 5), round(lon, 5)) for lon, lat in coords]
            _ROAD_CACHE[cache_key] = pts
            return pts, dist_km
    except Exception:
        # Fallback: intermediate curve point following general terrain axis
        mid_lat = (c1[0] + c2[0]) / 2.0
        mid_lon = (c1[1] + c2[1]) / 2.0
        pts = [c1, (mid_lat, mid_lon), c2]
        dist_km = road_distance_km(c1[0], c1[1], c2[0], c2[1])
        return pts, dist_km
